  constructor(public readonly auth: AuthService) {}

  isLocked(item: NavItem): boolean {
    if (!item.minPlan) return false;
    return !this.auth.hasPlanAccess(item.minPlan);
  }

  planLabel(plan: SubscriptionPlan | undefined, role?: string): string {
    if (role === 'admin') return 'Super Admin · Ilimitado';
    switch (plan) {
      case 'enterprise':
        return 'Plano Enterprise';
      case 'pro':
        return 'Plano Profissional';
      default:
        return 'Plano Básico';
    }
  }

  initials(name: string | null | undefined): string {
    if (!name) return 'P';
    return name
      .split(' ')
      .filter(Boolean)
      .slice(0, 2)
      .map((part) => part.charAt(0).toUpperCase())
      .join('');
  }

  logout(): void {
    this.auth.logout();
  }

  closeSidebar(): void {
    this.close.emit();
  }
